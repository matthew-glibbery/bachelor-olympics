/**
 * Selectable app themes — the groom-tools theme picker.
 *
 * "Classic" is this app's original hand-picked default (the values already
 * in globals.css). Everything else is a REAL tweakcn preset, fetched
 * verbatim from tweakcn.com's own registry (https://tweakcn.com/r/themes/
 * <slug>.json) on 2026-08-11 — not invented. Only the CSS variables this
 * app's globals.css actually declares are kept (tweakcn's export also
 * includes font/shadow/tracking vars this app doesn't use).
 *
 * Applying a theme means writing these as inline styles on
 * document.documentElement (see src/components/theme-applier.tsx) — that
 * overrides the static :root values in globals.css without needing a second
 * stylesheet. Dark-mode values are captured here for completeness (matching
 * a full tweakcn export) but not applied yet: this app has no dark-mode
 * toggle wired up (nothing ever adds the `.dark` class), so only `light` is
 * live right now.
 *
 * "Olympic" is hand-authored (like Classic), not a tweakcn preset — tweakcn
 * has nothing Olympics-themed. Built from the actual Olympic ring colors
 * (blue #0081C8, gold #FCB131, green #00A651, red #EE334E, near-black in
 * place of pure ring-black so it stays legible as chart-3 on a light card)
 * converted to oklch via the standard sRGB→OKLab→OKLCH path (no library
 * dependency added for one theme). Primary/accent/destructive map to
 * blue/gold/red so the app's own buttons and status colors read as
 * "Olympics", not just the chart legend.
 */

